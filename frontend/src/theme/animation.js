// Strips motion down to an instant, near-zero-duration crossfade for
// prefers-reduced-motion users while keeping the same variant shape.
export function withReducedMotion(variant, reduced) {
  if (!reduced) return variant;

  return {
    ...variant,
    initial: { opacity: variant.initial?.opacity ?? 0 },
    animate: { opacity: 1 },
    exit: { opacity: variant.exit?.opacity ?? 0 },
    transition: { duration: 0.01 },
  };
}
